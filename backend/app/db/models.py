from datetime import datetime, timezone
from typing import Dict, Optional, List, Any
import uuid

# In-memory storage dictionary for active sessions without hard DB dependencies
_IN_MEMORY_ANALYSES_DB: Dict[str, Dict[str, Any]] = {}


class AnalysisRecord:
    """
    Data record representation for Brain Tumor IDH Classification session.
    Prepares structure for SQLAlchemy ORM mapping when connecting to PostgreSQL.
    """

    def __init__(
        self,
        patient_reference: str,
        age: float,
        sex: str,
        prediction_class: int,
        prediction_label: str,
        wild_type_probability: float,
        mutated_probability: float,
        model_version: str = "1.0",
        analysis_id: Optional[str] = None,
        degraded_mode: bool = False,
        architecture: str = "MultimodalCNNViT",
    ):
        self.id = analysis_id or str(uuid.uuid4())
        self.patient_reference = patient_reference
        self.age = age
        self.sex = sex
        self.status = "completed"
        self.prediction_class = prediction_class
        self.prediction_label = prediction_label
        self.wild_type_probability = wild_type_probability
        self.mutated_probability = mutated_probability
        self.model_version = model_version
        self.degraded_mode = degraded_mode
        self.architecture = architecture
        self.created_at = datetime.now(timezone.utc).isoformat()
        self.completed_at = datetime.now(timezone.utc).isoformat()


    def to_dict(self) -> Dict[str, Any]:
        return {
            "analysis_id": self.id,
            "status": self.status,
            "created_at": self.created_at,
            "completed_at": self.completed_at,
            "patient": {
                "patient_id": self.patient_reference,
                "age": self.age,
                "sex": self.sex,
            },
            "mri_modalities": ["T1", "T1ce", "T2", "FLAIR"],
            "prediction": {
                "class": self.prediction_class,
                "label": self.prediction_label,
            },
            "probabilities": {
                "idh_wild_type": self.wild_type_probability,
                "idh_mutated": self.mutated_probability,
            },
            "model": {
                "name": "Multimodal CNN-Vision Transformer",
                "version": self.model_version,
                "architecture": self.architecture,
                "degraded_mode": self.degraded_mode,
            },
            "disclaimer": (
                "This application is a research and educational decision-support system. "
                "Its predictions are generated by a machine-learning model and should not be interpreted as a definitive medical diagnosis. "
                "Clinical decisions must be made by qualified healthcare professionals using appropriate clinical evidence."
            ),
        }


def save_analysis(record: AnalysisRecord) -> None:
    """Save record into in-memory store."""
    _IN_MEMORY_ANALYSES_DB[record.id] = record.to_dict()


def get_analysis_by_id(analysis_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve analysis record by ID."""
    return _IN_MEMORY_ANALYSES_DB.get(analysis_id)
