import json
from typing import Dict, Any


def generate_text_report(analysis_data: Dict[str, Any]) -> str:
    """
    Generate a formatted text report for printing or downloading.
    """
    patient = analysis_data.get("patient", {})
    pred = analysis_data.get("prediction", {})
    probs = analysis_data.get("probabilities", {})
    model = analysis_data.get("model", {})

    report_lines = [
        "================================================================================",
        "                  NEUROINSIGHT AI - IDH CLASSIFICATION REPORT                   ",
        "             Multimodal MRI + Clinical Data AI Decision Support                 ",
        "================================================================================",
        "",
        f"ANALYSIS ID      : {analysis_data.get('analysis_id', 'N/A')}",
        f"DATE / TIME      : {analysis_data.get('created_at', 'N/A')}",
        f"STATUS           : {analysis_data.get('status', 'COMPLETED').upper()}",
        "",
        "--------------------------------------------------------------------------------",
        "1. PATIENT INFORMATION",
        "--------------------------------------------------------------------------------",
        f"Patient Reference ID : {patient.get('patient_id', 'N/A')}",
        f"Age                  : {patient.get('age', 'N/A')} years",
        f"Sex                  : {patient.get('sex', 'N/A')}",
        "",
        "--------------------------------------------------------------------------------",
        "2. MRI INPUT MODALITIES",
        "--------------------------------------------------------------------------------",
        "Modalities Provided  : T1, T1ce, T2, FLAIR (3D NIfTI Volumes)",
        "Preprocessed Shape   : 4 x 128 x 128 x 96 (Float32 Normalized)",
        "",
        "--------------------------------------------------------------------------------",
        "3. MODEL PREDICTION & IDH CLASSIFICATION",
        "--------------------------------------------------------------------------------",
        f"Predicted Class      : {pred.get('label', 'N/A')}",
        f"IDH Wild Type Prob   : {probs.get('idh_wild_type', 0) * 100:.2f}%",
        f"IDH Mutated Prob     : {probs.get('idh_mutated', 0) * 100:.2f}%",
        "",
        "--------------------------------------------------------------------------------",
        "4. MODEL DETAILS",
        "--------------------------------------------------------------------------------",
        f"Architecture         : {model.get('name', 'Multimodal CNN-Vision Transformer')}",
        f"Model Version        : {model.get('version', '1.0')}",
        f"Mode                 : {'Degraded (Placeholder weights)' if model.get('degraded_mode') else 'Production Model Checkpoint'}",
        "",
        "================================================================================",
        "                               IMPORTANT DISCLAIMER                              ",
        "================================================================================",
        analysis_data.get(
            "disclaimer",
            "This application is a research and educational decision-support system. "
            "Its predictions are generated by a machine-learning model and should not be "
            "interpreted as a definitive medical diagnosis. Clinical decisions must be made "
            "by qualified healthcare professionals using appropriate clinical evidence."
        ),
        "================================================================================",
    ]
    return "\n".join(report_lines)
