from datetime import datetime
from typing import Dict, Any, Optional
from pydantic import BaseModel, Field, ConfigDict


class PatientInput(BaseModel):
    patient_id: str = Field(..., description="Anonymized patient reference identifier")
    age: float = Field(..., ge=0, le=120, description="Patient age in years")
    sex: str = Field(..., description="Patient sex ('Male' or 'Female')")


class ModelInfo(BaseModel):
    name: str = "Multimodal CNN-Vision Transformer"
    version: str = "1.0"
    architecture: str = "MultimodalCNNViT"
    degraded_mode: bool = False
    scaler_configured: bool = False
    explainability_ready: bool = False


class PredictionProbability(BaseModel):
    idh_wild_type: float = Field(..., ge=0.0, le=1.0)
    idh_mutated: float = Field(..., ge=0.0, le=1.0)


class PredictionResult(BaseModel):
    prediction_class: int = Field(..., alias="class", description="0 for IDH Wild Type, 1 for IDH Mutated")
    label: str = Field(..., description="IDH Wild Type or IDH Mutated")

    model_config = ConfigDict(populate_by_name=True)



class AnalysisResponse(BaseModel):
    analysis_id: str
    status: str = "completed"
    created_at: str
    patient: PatientInput
    mri_modalities: list[str] = ["T1", "T1ce", "T2", "FLAIR"]
    prediction: PredictionResult
    probabilities: PredictionProbability
    model: ModelInfo
    disclaimer: str = (
        "This application is a research and educational decision-support system. "
        "Its predictions are generated by a machine-learning model and should not be interpreted as a definitive medical diagnosis. "
        "Clinical decisions must be made by qualified healthcare professionals using appropriate clinical evidence."
    )


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    age_scaler_configured: bool
    checkpoint_path: str
    config_path: str
    device: str
    details: Dict[str, Any]


class ErrorResponse(BaseModel):
    detail: str
    error_code: Optional[str] = None
    timestamp: str
